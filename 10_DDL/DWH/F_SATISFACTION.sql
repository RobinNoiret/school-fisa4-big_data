CREATE TABLE FAIT_SATISFACTION(
   ID_SATISFACTION INT,
   LB_TYPE_ENQUETE VARCHAR(30),
   SC_GLOBAL DECIMAL(5,2),
   SC_ACCUEIL DECIMAL(5,2),
   SC_PEC_INFIRMIER DECIMAL(5,2),
   SC_PEC_MEDICAL DECIMAL(5,2),
   SC_CHAMBRE DECIMAL(5,2),
   SC_REPAS DECIMAL(5,2),
   SC_SORTIE DECIMAL(5,2),
   RT_RECOMMANDATION DECIMAL(5,2),
   NB_REPONDANTS INT,
   LB_CLASSEMENT CHAR(1),
   SK_LOCALISATION INT NOT NULL,
   SK_ETABLISSEMENT INT NOT NULL,
   ID_TEMPS INT NOT NULL,
   PRIMARY KEY(ID_SATISFACTION),
   FOREIGN KEY(SK_LOCALISATION) REFERENCES DIM_LOCALISATION(SK_LOCALISATION),
   FOREIGN KEY(SK_ETABLISSEMENT) REFERENCES DIM_ETABLISSEMENT(SK_ETABLISSEMENT),
   FOREIGN KEY(ID_TEMPS) REFERENCES DIM_TEMPS(ID_TEMPS)
);
