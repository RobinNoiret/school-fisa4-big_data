CREATE TABLE FAIT_CONSULTATION(
   ID_CONSULTATION INT,
   LB_MOTIF VARCHAR(255),
   NB_AGE_PATIENT INT,
   LB_TRANCHE_AGE VARCHAR(10),
   DUR_CONSULTATION INT,
   NB_CONSULTATION INT,
   SK_LOCALISATION INT NOT NULL,
   SK_ETABLISSEMENT INT NOT NULL,
   SK_DIAGNOSTIC INT NOT NULL,
   SK_PROFESSIONNEL INT NOT NULL,
   SK_PATIENT INT NOT NULL,
   ID_TEMPS INT NOT NULL,
   PRIMARY KEY(ID_CONSULTATION),
   FOREIGN KEY(SK_LOCALISATION) REFERENCES DIM_LOCALISATION(SK_LOCALISATION),
   FOREIGN KEY(SK_ETABLISSEMENT) REFERENCES DIM_ETABLISSEMENT(SK_ETABLISSEMENT),
   FOREIGN KEY(SK_DIAGNOSTIC) REFERENCES DIM_DIAGNOSTIC(SK_DIAGNOSTIC),
   FOREIGN KEY(SK_PROFESSIONNEL) REFERENCES DIM_PROFESSIONNEL(SK_PROFESSIONNEL),
   FOREIGN KEY(SK_PATIENT) REFERENCES DIM_PATIENT(SK_PATIENT),
   FOREIGN KEY(ID_TEMPS) REFERENCES DIM_TEMPS(ID_TEMPS)
);
