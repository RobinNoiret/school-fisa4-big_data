-- REFINED -> DWH | dim_temps

WITH date_ranges AS (
    SELECT DT_DEBUT,
           DT_FIN
    FROM chu_refined.corporate_system_date
    WHERE FL_ACTIVE = TRUE AND DT_DEBUT IS NOT NULL AND DT_FIN IS NOT NULL AND DT_DEBUT <= DT_FIN
),

jours AS (
    SELECT DATE_ADD(DT_DEBUT, pos) AS DT_JOUR
    FROM date_ranges
    LATERAL VIEW POSEXPLODE(SPLIT(REPEAT('x,', DATEDIFF(DT_FIN, DT_DEBUT) + 1), ','))
        generated AS pos,
        ignored
),

jours_distinct AS (
    SELECT DISTINCT DT_JOUR
    FROM jours
)

INSERT OVERWRITE TABLE chu_dwh.dim_temps

SELECT
    CAST(FROM_UNIXTIME(UNIX_TIMESTAMP(DT_JOUR), 'yyyyMMdd') AS INT) AS ID_DIM_TEMPS,
    DT_JOUR AS DT_JOUR,
    DAY(DT_JOUR) AS NB_JOUR,
    CASE PMOD(DATEDIFF(DT_JOUR, '1970-01-05'), 7) WHEN 0 THEN 'LUNDI' WHEN 1 THEN 'MARDI' WHEN 2 THEN 'MERCREDI' WHEN 3 THEN 'JEUDI' WHEN 4 THEN 'VENDREDI' WHEN 5 THEN 'SAMEDI' WHEN 6 THEN 'DIMANCHE' END AS NM_JOUR_SEMAINE,
    MONTH(DT_JOUR) AS NB_MOIS,
    CASE MONTH(DT_JOUR) WHEN 1 THEN 'JANVIER' WHEN 2 THEN 'FEVRIER' WHEN 3 THEN 'MARS' WHEN 4 THEN 'AVRIL' WHEN 5 THEN 'MAI' WHEN 6 THEN 'JUIN' WHEN 7 THEN 'JUILLET' WHEN 8 THEN 'AOUT' WHEN 9 THEN 'SEPTEMBRE' WHEN 10 THEN 'OCTOBRE' WHEN 11 THEN 'NOVEMBRE' WHEN 12 THEN 'DECEMBRE' END AS NM_MOIS,
    YEAR(DT_JOUR) AS NB_ANNEE,
    CASE WHEN PMOD(DATEDIFF(DT_JOUR, '1970-01-05'), 7) IN (5, 6) THEN TRUE ELSE FALSE END AS FL_WEEK_END
FROM jours_distinct;
