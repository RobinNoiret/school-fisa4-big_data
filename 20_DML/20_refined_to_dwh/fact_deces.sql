-- REFINED -> DWH | fact_deces

WITH deces_source AS (
    SELECT TRIM(NB_ACTE_DECES) AS NB_ACTE_DECES,
           UPPER(TRIM(CD_LIEU_DECES)) AS CD_LIEU_DECES,
           UPPER(TRIM(NM_PAYS)) AS NM_PAYS_NAISSANCE,
           CAST(NM_SEXE AS STRING) AS CD_SEXE_SOURCE,
           DT_NAISSANCE,
           DT_DECES
    FROM chu_refined.demographie_insee_deces
    WHERE FL_ACTIVE = TRUE AND NB_ACTE_DECES IS NOT NULL AND DT_DECES IS NOT NULL
),

deces_prepared AS (
    SELECT NB_ACTE_DECES,
           CASE WHEN SUBSTR(CD_LIEU_DECES, 1, 3) IN ('971', '972', '973', '974', '975', '976', '977', '978') THEN SUBSTR(CD_LIEU_DECES, 1, 3) ELSE SUBSTR(CD_LIEU_DECES, 1, 2) END AS CD_DEPARTEMENT_DECES,
           NM_PAYS_NAISSANCE,
           CASE CD_SEXE_SOURCE WHEN '1' THEN 'M' WHEN '2' THEN 'F' ELSE CD_SEXE_SOURCE END AS CD_SEXE,
           DT_DECES AS NB_ANNEE_DECES,
           CASE WHEN DT_NAISSANCE IS NOT NULL AND DT_DECES >= DT_NAISSANCE THEN DT_DECES - DT_NAISSANCE ELSE NULL END AS NB_AGE_DECES
    FROM deces_source
)

INSERT OVERWRITE TABLE chu_dwh.fait_deces (
    ID_FAIT_DECES,
    FK_DIM_DEPARTEMENT_DECES,
    FK_DIM_PAYS_NAISSANCE,
    CD_SEXE,
    NB_ANNEE_DECES,
    NB_AGE_DECES
)

SELECT ROW_NUMBER() OVER (ORDER BY src.NB_ACTE_DECES),
       departement.ID_DIM_DEPARTEMENT,
       pays.ID_DIM_PAYS,
       src.CD_SEXE,
       src.NB_ANNEE_DECES,
       src.NB_AGE_DECES
    FROM deces_prepared src
INNER JOIN chu_dwh.dim_departement departement ON departement.CD_DEPARTEMENT = src.CD_DEPARTEMENT_DECES
INNER JOIN chu_dwh.dim_pays pays ON pays.NM_PAYS = src.NM_PAYS_NAISSANCE;
