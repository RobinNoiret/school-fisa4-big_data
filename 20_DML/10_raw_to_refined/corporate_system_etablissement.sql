-- RAW -> REFINED | corporate_system_etablissement

WITH source_raw AS (
    SELECT ID_TECH,
           TXT_CEDEX,
           CD_COMMUNE,
           CD_POSTAL,
           TXT_COMMUNE,
           TXT_COMPLEMENT_DESTINATION,
           TXT_POINT_GEOGRAPHIQUE,
           TXT_EMAIL,
           NM_ENSEIGNE_COMMERCIALE_SITE,
           CD_ETABLISSEMENT_JURIDIQUE,
           CD_SITE,
           ID_ORGANISATION,
           NB_REPETITION_VOIE,
           TXT_MENTION_DISTRIBUTION,
           NB_VOIE,
           NM_PAYS,
           TXT_RAISON_SOCIALE,
           NB_SIREN_SITE,
           NB_SIRET_SITE,
           TXT_TELECOPIE,
           NB_TEL,
           NB_TEL_BIS,
           NM_TYPE_VOIE,
           TXT_VOIE,
           INPUT__FILE__NAME AS NM_FILE
    FROM chu_raw.corporate_system_etablissement
    WHERE ID_ORGANISATION IS NOT NULL
),

prepared AS (
    SELECT ID_TECH,
           TRIM(TXT_CEDEX) AS TXT_CEDEX,
           UPPER(TRIM(CD_COMMUNE)) AS CD_COMMUNE,
           UPPER(TRIM(CD_POSTAL)) AS CD_POSTAL,
           UPPER(TRIM(TXT_COMMUNE)) AS TXT_COMMUNE,
           TRIM(TXT_COMPLEMENT_DESTINATION) AS TXT_COMPLEMENT_DESTINATION,
           TRIM(TXT_POINT_GEOGRAPHIQUE) AS TXT_POINT_GEOGRAPHIQUE,
           LOWER(TRIM(TXT_EMAIL)) AS TXT_EMAIL,
           UPPER(TRIM(NM_ENSEIGNE_COMMERCIALE_SITE)) AS NM_ENSEIGNE_COMMERCIALE_SITE,
           UPPER(TRIM(CD_ETABLISSEMENT_JURIDIQUE)) AS CD_ETABLISSEMENT_JURIDIQUE,
           UPPER(TRIM(CD_SITE)) AS CD_SITE,
           TRIM(ID_ORGANISATION) AS ID_ORGANISATION,
           TRIM(NB_REPETITION_VOIE) AS NB_REPETITION_VOIE,
           TRIM(TXT_MENTION_DISTRIBUTION) AS TXT_MENTION_DISTRIBUTION,
           TRIM(NB_VOIE) AS NB_VOIE,
           UPPER(TRIM(NM_PAYS)) AS NM_PAYS,
           UPPER(TRIM(TXT_RAISON_SOCIALE)) AS TXT_RAISON_SOCIALE,
           TRIM(NB_SIREN_SITE) AS NB_SIREN_SITE,
           TRIM(NB_SIRET_SITE) AS NB_SIRET_SITE,
           TRIM(TXT_TELECOPIE) AS TXT_TELECOPIE,
           TRIM(NB_TEL) AS NB_TEL,
           TRIM(NB_TEL_BIS) AS NB_TEL_BIS,
           UPPER(TRIM(NM_TYPE_VOIE)) AS NM_TYPE_VOIE,
           UPPER(TRIM(TXT_VOIE)) AS TXT_VOIE,
           NM_FILE
    FROM source_raw
),

deduplicated AS (
    SELECT ID_TECH,
           TXT_CEDEX,
           CD_COMMUNE,
           CD_POSTAL,
           TXT_COMMUNE,
           TXT_COMPLEMENT_DESTINATION,
           TXT_POINT_GEOGRAPHIQUE,
           TXT_EMAIL,
           NM_ENSEIGNE_COMMERCIALE_SITE,
           CD_ETABLISSEMENT_JURIDIQUE,
           CD_SITE,
           ID_ORGANISATION,
           NB_REPETITION_VOIE,
           TXT_MENTION_DISTRIBUTION,
           NB_VOIE,
           NM_PAYS,
           TXT_RAISON_SOCIALE,
           NB_SIREN_SITE,
           NB_SIRET_SITE,
           TXT_TELECOPIE,
           NB_TEL,
           NB_TEL_BIS,
           NM_TYPE_VOIE,
           TXT_VOIE,
           NM_FILE,
           ROW_NUMBER() OVER (PARTITION BY ID_ORGANISATION ORDER BY NM_FILE DESC, ID_TECH DESC) AS RN
    FROM prepared
)

INSERT OVERWRITE TABLE chu_refined.corporate_system_etablissement (
    ID_TECH,
    TXT_CEDEX,
    CD_COMMUNE,
    CD_POSTAL,
    TXT_COMMUNE,
    TXT_COMPLEMENT_DESTINATION,
    TXT_POINT_GEOGRAPHIQUE,
    TXT_EMAIL,
    NM_ENSEIGNE_COMMERCIALE_SITE,
    CD_ETABLISSEMENT_JURIDIQUE,
    CD_SITE,
    ID_ORGANISATION,
    NB_REPETITION_VOIE,
    TXT_MENTION_DISTRIBUTION,
    NB_VOIE,
    NM_PAYS,
    TXT_RAISON_SOCIALE,
    NB_SIREN_SITE,
    NB_SIRET_SITE,
    TXT_TELECOPIE,
    NB_TEL,
    NB_TEL_BIS,
    NM_TYPE_VOIE,
    TXT_VOIE,
    FL_ACTIVE,
    NM_FILE,
    NM_PROVIDER
)

SELECT ID_TECH,
       TXT_CEDEX,
       CD_COMMUNE,
       CD_POSTAL,
       TXT_COMMUNE,
       TXT_COMPLEMENT_DESTINATION,
       TXT_POINT_GEOGRAPHIQUE,
       TXT_EMAIL,
       NM_ENSEIGNE_COMMERCIALE_SITE,
       CD_ETABLISSEMENT_JURIDIQUE,
       CD_SITE,
       ID_ORGANISATION,
       NB_REPETITION_VOIE,
       TXT_MENTION_DISTRIBUTION,
       NB_VOIE,
       NM_PAYS,
       TXT_RAISON_SOCIALE,
       NB_SIREN_SITE,
       NB_SIRET_SITE,
       TXT_TELECOPIE,
       NB_TEL,
       NB_TEL_BIS,
       NM_TYPE_VOIE,
       TXT_VOIE,
       CAST(1 AS BOOLEAN),
       NM_FILE,
       'system'
    FROM deduplicated
WHERE RN = 1;
