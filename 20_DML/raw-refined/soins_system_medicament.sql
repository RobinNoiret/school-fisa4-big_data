-- RAW -> REFINED | soins_system_medicament

WITH source_raw AS (
    SELECT ID_TECH,
           CD_CIS,
           NM_MEDICAMENT,
           TXT_FORME_PHARMA,
           TXT_VOIES_ADMINISTRATION,
           TXT_STATUT_ADMIN,
           TXT_TYPE_PROCEDURE,
           FL_COMMERCIALISATION,
           DT_AMM,
           TXT_STATUT_BDM,
           CD_AUTORISATION_EURO,
           NM_TITULAIRE,
           FL_SURVEILLANCE_RENFORCEE,
           INPUT__FILE__NAME AS NM_FILE
    FROM chu_raw.soins_system_medicament
    WHERE CD_CIS IS NOT NULL
),

prepared AS (
    SELECT ID_TECH,
           UPPER(TRIM(CD_CIS)) AS CD_CIS,
           UPPER(TRIM(NM_MEDICAMENT)) AS NM_MEDICAMENT,
           UPPER(TRIM(TXT_FORME_PHARMA)) AS TXT_FORME_PHARMA,
           UPPER(TRIM(TXT_VOIES_ADMINISTRATION)) AS TXT_VOIES_ADMINISTRATION,
           UPPER(TRIM(TXT_STATUT_ADMIN)) AS TXT_STATUT_ADMIN,
           UPPER(TRIM(TXT_TYPE_PROCEDURE)) AS TXT_TYPE_PROCEDURE,
           FL_COMMERCIALISATION,
           DT_AMM,
           UPPER(TRIM(TXT_STATUT_BDM)) AS TXT_STATUT_BDM,
           UPPER(TRIM(CD_AUTORISATION_EURO)) AS CD_AUTORISATION_EURO,
           UPPER(TRIM(NM_TITULAIRE)) AS NM_TITULAIRE,
           FL_SURVEILLANCE_RENFORCEE,
           NM_FILE
    FROM source_raw
),

deduplicated AS (
    SELECT ID_TECH,
           CD_CIS,
           NM_MEDICAMENT,
           TXT_FORME_PHARMA,
           TXT_VOIES_ADMINISTRATION,
           TXT_STATUT_ADMIN,
           TXT_TYPE_PROCEDURE,
           FL_COMMERCIALISATION,
           DT_AMM,
           TXT_STATUT_BDM,
           CD_AUTORISATION_EURO,
           NM_TITULAIRE,
           FL_SURVEILLANCE_RENFORCEE,
           NM_FILE,
           ROW_NUMBER() OVER (PARTITION BY CD_CIS ORDER BY NM_FILE DESC, ID_TECH DESC) AS RN
    FROM prepared
)

INSERT OVERWRITE TABLE chu_refined.soins_system_medicament

SELECT
    ID_TECH AS ID_TECH,
    CD_CIS AS CD_CIS,
    NM_MEDICAMENT AS NM_MEDICAMENT,
    TXT_FORME_PHARMA AS TXT_FORME_PHARMA,
    TXT_VOIES_ADMINISTRATION AS TXT_VOIES_ADMINISTRATION,
    TXT_STATUT_ADMIN AS TXT_STATUT_ADMIN,
    TXT_TYPE_PROCEDURE AS TXT_TYPE_PROCEDURE,
    FL_COMMERCIALISATION AS FL_COMMERCIALISATION,
    DT_AMM AS DT_AMM,
    TXT_STATUT_BDM AS TXT_STATUT_BDM,
    CD_AUTORISATION_EURO AS CD_AUTORISATION_EURO,
    NM_TITULAIRE AS NM_TITULAIRE,
    FL_SURVEILLANCE_RENFORCEE AS FL_SURVEILLANCE_RENFORCEE,
    CAST(1 AS BOOLEAN) AS FL_ACTIVE,
    NM_FILE AS NM_FILE,
    'system' AS NM_PROVIDER
FROM deduplicated
WHERE RN = 1;
